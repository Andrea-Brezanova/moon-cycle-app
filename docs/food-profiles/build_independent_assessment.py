#!/usr/bin/env python3
"""Builds phase-independent-assessment.json and .md: an evidence-based review of the 142 phase-assigned foods.

Run from the repo root:  python3 docs/food-profiles/build_independent_assessment.py
It does not change any phase assignment (proposedPhaseChange is always null) and it does not use or reproduce
any other author's list. Nutrient facts come from the verified USDA/NIH profile data; the research statements
come from docs/food-profiles/independent-phase-methodology.md.
"""
import collections, json

R = 'docs/food-profiles/'
foods = {f['id']: f for f in json.load(open('assets/content/foods.json'))['foods']}
phase = {k: list(f['why'])[0] for k, f in foods.items() if f['why']}
drafts = json.load(open(R + 'complete-draft-dataset.json'))['profiles']
approved = json.load(open('assets/content/food_profiles.json'))['profiles']
SEEDS = {'flaxseeds', 'pumpkin-seeds', 'sesame-seeds', 'sunflower-seeds'}


def per_serving(fid):
    return (drafts.get(fid) or approved[fid])['perServing']


def sources_of(fid):
    ks = per_serving(fid)['keyNutrients']
    out = []
    for n in ks:
        pct = n['reference'][0]['percent'] if n.get('reference') else None
        out.append(dict(nutrient=n['name'], amount=f"{n['amount']} {n['unit']}", percentOfReference=pct))
    return out


rows = []
for fid in sorted(phase, key=lambda k: (phase[k], k)):
    ps = per_serving(fid)
    ks = sources_of(fid)
    big = [k for k in ks if (k['percentOfReference'] or 0) >= 15]
    iron = next((k for k in ks if k['nutrient'] == 'Iron' and (k['percentOfReference'] or 0) >= 10), None)
    calcium = next((k for k in ks if k['nutrient'] == 'Calcium' and (k['percentOfReference'] or 0) >= 10), None)
    ph = phase[fid]
    topics = []
    if iron:
        topics.append('Iron: needs are higher for people who menstruate (NIH ODS) and apply every day of the month; no research found that timing within the cycle matters.')
    if calcium and ph == 'luteal':
        topics.append('Calcium and premenstrual symptoms: one large trial used a 1,200 mg supplement; no food-based or timing evidence.')
    if fid in SEEDS:
        topics.append('Seed cycling: small, mixed studies of seeds or their components in PMS/PCOS populations; the phase rotation itself is not separately tested.')
    if fid in SEEDS:
        basis = 'traditional-association'
        cls = 'R3 traditional association; keep only as a variety suggestion, no claim'
        action = 'owner decision: whether to keep the seed pairing at all'
    elif big:
        basis = 'general-editorial-suggestion'
        cls = 'R1 nutrient-informed variety suggestion (a good source of ' + ', '.join(k['nutrient'].lower() for k in big[:3]) + ')'
        action = 'retain for now; record this rationale'
    else:
        basis = 'general-editorial-suggestion'
        cls = 'R2 variety and meal-fit suggestion (no standout nutrient)'
        action = 'retain for now; record this rationale'
    rows.append(dict(
        id=fid, name=foods[fid]['name'], existingPhase=ph,
        generalNutritionalBenefits=[f"{k['nutrient']} {k['amount']}" + (f" ({k['percentOfReference']}% of the reference)" if k['percentOfReference'] else '') for k in ks],
        phaseDependentResearch='none identified',
        relatedResearchTopics=topics,
        existingBasis=basis, scientificallySupportedAsPhaseSpecific=False,
        proposedIndependentClassification=cls, proposedPhaseChange=None, suggestedReviewAction=action,
        sources=['USDA FoodData Central (profile record)', 'NIH ODS reference intakes'] + (['NIH ODS Iron'] if iron else []),
        limitations='Per-serving figures describe one serving of the recorded preparation. A featured phase is an editorial suggestion for variety, not a requirement.'))

summ = dict(foods=len(rows), perPhase=dict(collections.Counter(r['existingPhase'] for r in rows)),
            byClass=dict(collections.Counter(r['proposedIndependentClassification'].split(' ')[0] for r in rows)),
            byBasis=dict(collections.Counter(r['existingBasis'] for r in rows)),
            supportedAsPhaseSpecific=sum(r['scientificallySupportedAsPhaseSpecific'] for r in rows),
            phaseChangesProposed=sum(1 for r in rows if r['proposedPhaseChange']))
json.dump(dict(_about='Independent review of the 142 phase-assigned foods. No phase is changed. See independent-phase-methodology.md.', summary=summ, foods=rows),
          open(R + 'phase-independent-assessment.json', 'w'), indent=1, ensure_ascii=False)

L = ['# Phase-assigned foods: independent assessment (142)\n',
     'Generated by `build_independent_assessment.py`. **No phase is changed and none is proposed.** "Classification" describes the *basis* on which a food could responsibly be featured, using the classes in `independent-phase-methodology.md`. Detail per food: `phase-independent-assessment.json`.\n',
     f'- Foods: {summ["foods"]}. Supported by reliable research as phase-specific: **{summ["supportedAsPhaseSpecific"]}**. Phase changes proposed: **{summ["phaseChangesProposed"]}**.',
     f'- Classes: ' + ', '.join(f'{k} {v}' for k, v in sorted(summ['byClass'].items())) + '.',
     '- R1 nutrient-informed variety suggestion (a good source, 15% or more of a reference per serving, of a nutrient). R2 variety and meal-fit suggestion. R3 traditional association, kept only as a variety suggestion.\n',
     '| Food | Existing phase | Classification | What a serving provides | Related research (not phase-timed) | Review action |', '|---|---|---|---|---|---|']
for r in rows:
    L.append(f"| {r['name']} (`{r['id']}`) | {r['existingPhase']} | {r['proposedIndependentClassification'].split(' ')[0]} | {'; '.join(r['generalNutritionalBenefits'][:3])} | {' '.join(t.split(':')[0] for t in r['relatedResearchTopics']) or '-'} | {r['suggestedReviewAction'].split(';')[0]} |")
open(R + 'phase-independent-assessment.md', 'w').write('\n'.join(L) + '\n')
print(json.dumps(summ))
